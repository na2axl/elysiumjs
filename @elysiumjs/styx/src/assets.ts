import { existsSync } from 'node:fs';
import { dirname, join } from 'node:path';

/**
 * The files Styx ships beside its code: the code generator stubs (`stubs/`) and the project
 * templates of `styx create` (`templates/`). They are read from the package folder, or from the
 * asset loader that Hephaestus embeds in the standalone executables.
 */

/**
 * The asset loader generated by Hephaestus (`AssetEmbedder`), keyed by the path in the package.
 * @author Axel Nana <axel.nana@workbud.com>
 */
export type EmbeddedAssets = {
	getAssetString(path: string): string | null;
	listAssets(): string[];
};

let embedded: EmbeddedAssets | undefined;

/**
 * Uses the assets embedded in a standalone executable. Called by its entry point.
 * @author Axel Nana <axel.nana@workbud.com>
 * @param assets The asset loader generated by Hephaestus.
 */
export const useEmbeddedAssets = (assets: EmbeddedAssets | undefined): void => {
	embedded = assets;
};

/** Finds the folder of the styx package, walking up from this file (`src/` or `dist/`). */
const findPackageRoot = (): string => {
	let dir = import.meta.dir;
	while (!existsSync(join(dir, 'stubs')) || !existsSync(join(dir, 'package.json'))) {
		const parent = dirname(dir);
		if (parent === dir) throw new Error('Could not find the files of the styx package.');
		dir = parent;
	}
	return dir;
};

let packageRoot: string | undefined;

/** The path of an asset in the package folder. */
const assetPath = (path: string): string => {
	packageRoot ??= findPackageRoot();
	return join(packageRoot, path);
};

/**
 * Reads an asset as text.
 * @author Axel Nana <axel.nana@workbud.com>
 * @param path The path of the asset in the package, such as `stubs/job.stub`.
 */
export const readAsset = async (path: string): Promise<string> => {
	if (embedded) {
		const text = embedded.getAssetString(path);
		if (text === null) throw new Error(`Styx has no file ${path}.`);
		return text;
	}
	return Bun.file(assetPath(path)).text();
};

/**
 * Lists the assets under a folder, with their paths relative to it.
 * @author Axel Nana <axel.nana@workbud.com>
 * @param folder The folder in the package, such as `templates/template-single`.
 */
export const listAssets = async (folder: string): Promise<string[]> => {
	const prefix = `${folder}/`;
	if (embedded) {
		return embedded
			.listAssets()
			.map((path) => path.replaceAll('\\', '/'))
			.filter((path) => path.startsWith(prefix))
			.map((path) => path.slice(prefix.length))
			.sort();
	}
	const root = assetPath(folder);
	if (!existsSync(root)) return [];
	const files = await Array.fromAsync(new Bun.Glob('**').scan({ cwd: root, dot: true }));
	return files.map((path) => path.replaceAll('\\', '/')).sort();
};
