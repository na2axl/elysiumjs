/**
 * Builds one Worker per conformance scenario, compiled ahead of time with `elysia/plugin/aot`
 * for workerd, into `.aot/<index>/worker.js`. The workerd AOT lane (vitest.workerd-aot.config.ts)
 * runs them without code generation from strings, as a deployed Worker runs.
 *
 * Each scenario builds in a process of its own: the AOT plugin imports the entry to capture its
 * routes, and the container is global to the process.
 *
 * `bun scripts/build-aot.ts` builds every scenario; `bun scripts/build-aot.ts <index>` builds one.
 */

import { mkdir, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import { aot } from 'elysia/plugin/aot/bun';

import { scenarios } from '../src/scenarios';

const root = join(import.meta.dir, '..', '.aot');

/** The entry of one scenario's Worker. `GET /__after` runs the scenario's `after` assertions. */
const entrySource = (index: number) => `// Generated by scripts/build-aot.ts.
import { Runtime } from '@elysiumjs/olympus';
import { createWorker, runtime } from '@elysiumjs/workers';

import { scenarios } from '../../src/scenarios';

Runtime.use(runtime);

const scenario = scenarios[${index}];
const application = await scenario.app();
const worker = await createWorker(application);

export const app = worker.app;

export default {
	async fetch(request, env, ctx) {
		if (new URL(request.url).pathname !== '/__after') return worker.fetch(request, env, ctx);
		const failures = [];
		const equal = (a, b, msg) => {
			if (JSON.stringify(a) !== JSON.stringify(b))
				failures.push(msg + ': ' + JSON.stringify(a) + ' !== ' + JSON.stringify(b));
		};
		try {
			await scenario.after?.(application, { equal });
		} catch (error) {
			failures.push(String(error?.stack ?? error));
		}
		return Response.json(failures);
	}
};
`;

const buildOne = async (index: number) => {
	const dir = join(root, String(index));
	await mkdir(dir, { recursive: true });
	const entry = join(dir, 'entry.ts');
	await writeFile(entry, entrySource(index));

	const result = await Bun.build({
		entrypoints: [entry],
		outdir: dir,
		naming: 'worker.js',
		target: 'browser',
		format: 'esm',
		conditions: ['workerd', 'worker', 'browser'],
		external: ['node:*', 'cloudflare:*'],
		plugins: [aot(entry, { target: 'workerd', strip: true })]
	});
	if (!result.success) {
		for (const log of result.logs) console.error(log);
		throw new Error(`Could not compile "${scenarios[index]!.name}" ahead of time.`);
	}

	const bundle = await Bun.file(join(dir, 'worker.js')).text();
	if (/\bnew Function\b|\beval\(/.test(bundle)) {
		throw new Error(`The Worker of "${scenarios[index]!.name}" generates code at runtime.`);
	}
};

const only = process.argv[2];

if (only !== undefined) {
	await buildOne(Number(only));
	// The AOT plugin keeps a worker alive.
	process.exit(0);
}

await rm(root, { recursive: true, force: true });
const failed: string[] = [];
await Promise.all(
	scenarios.map(async (scenario, index) => {
		const proc = Bun.spawn([process.execPath, import.meta.path, String(index)], {
			stdout: 'inherit',
			stderr: 'inherit'
		});
		if ((await proc.exited) !== 0) failed.push(scenario.name);
	})
);
await writeFile(join(root, 'scenarios.json'), JSON.stringify(scenarios.map((s) => s.name)));

if (failed.length > 0) {
	console.error(`Could not build: ${failed.join(', ')}`);
	process.exit(1);
}
console.log(`Built ${scenarios.length} AOT Workers into .aot/.`);
process.exit(0);
